// ── Helper Functions ──────────────────────────────────────────────────────

export function getAllOwners() {
  return [...BUSINESS_OWNERS]
}

export function getOwnerById(ownerId) {
  return BUSINESS_OWNERS.find((o) => o.id === ownerId) || null
}

export function updateOwnerStatus(ownerId, status) {
  const owner = BUSINESS_OWNERS.find((o) => o.id === ownerId)
  if (owner) {
    owner.accountStatus = status
    owner.updatedAt = new Date().toISOString()
  }
  return owner
}

export function getAllSubmissions() {
  return [...BUSINESS_SUBMISSIONS]
}

export function getSubmissionById(id) {
  return BUSINESS_SUBMISSIONS.find((s) => s.id === id) || null
}

export function getSubmissionsByStatus(status) {
  return BUSINESS_SUBMISSIONS.filter((s) => s.status === status)
}

export function getPendingCount() {
  return BUSINESS_SUBMISSIONS.filter((s) => s.status === 'pending').length
}

export function updateSubmissionStatus(id, status, rejectionReason = null) {
  const submission = BUSINESS_SUBMISSIONS.find((s) => s.id === id)
  if (submission) {
    submission.status = status
    submission.rejectionReason = rejectionReason
    submission.updatedAt = new Date().toISOString()
  }
  return submission
}

export function getUniqueCategories() {
  const cats = new Set(BUSINESS_SUBMISSIONS.map((s) => s.category))
  return [...cats].sort()
}

export function getUniqueCities() {
  const cities = new Set(BUSINESS_SUBMISSIONS.map((s) => s.city))
  return [...cities].sort()
}
